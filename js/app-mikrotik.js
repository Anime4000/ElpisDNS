async function resolveDomain(domain, type){

    try{

        const response = await fetch(
            `https://dns.google/resolve?name=${domain}&type=${type}`
        );

        const data = await response.json();

        if(!data.Answer)
            return [];

        return data.Answer
            .filter(x => x.type === type)
            .map(x => x.data);

    } catch(err){

        console.error(err);

        return [];
    }
}

async function generateMikrotikRSC(){

    const endpoint =
        document.getElementById("endpoint")
            .innerText;

    const url = new URL(endpoint);

    const domain = url.hostname;

    const ipv4 = await resolveDomain(domain, 1);
    const ipv6 = await resolveDomain(domain, 28);

    let rsc = "";

    rsc +=
        `# Mikrotik RSC file for ${domain}\n` +
        `# Generated on ${new Date().toLocaleString()}\n` +
        `# This file adds static DNS entries for ${domain} and configures DoH\n` +
        `# Note: This will overwrite existing DoH settings on the router\n` +
        `# Script generated by ELPIS DNS (Anime4000)\n\n` +
        `/ip dns static remove [ find name="${domain}" ]\n\n`;

    // IPv4
    ipv4.forEach(ip => {

        rsc +=
            `/ip dns static add name="${domain}" type=A address="${ip}"\n`;
    });

    // IPv6
    ipv6.forEach(ip => {

        rsc +=
            `/ip dns static add name="${domain}" type=AAAA address="${ip}"\n`;
    });

    // DoH
    rsc +=
        `/ip dns set use-doh-server="${endpoint}" allow-remote-requests=yes verify-doh-cert=yes\n`;

    // Download
    const blob = new Blob([rsc], {
        type: "text/plain"
    });

    const link = document.createElement("a");

    link.href = URL.createObjectURL(blob);

    link.download = `${domain}.rsc`;

    document.body.appendChild(link);

    link.click();

    document.body.removeChild(link);
}

// Button

document
    .getElementById("download-rsc-btn")
    .onclick = generateMikrotikRSC;